// Copies the reviewed legal drafts (docs/autofix/legal/*.md) into
// src/lib/legal/sources.generated.ts so the app renders exactly that text.
// Run after editing a draft: `node scripts/sync-legal-copy.mjs`.
// src/__tests__/legal-copy.test.ts fails while the two differ.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const files = {
  privacyNotice: "docs/autofix/legal/privacy-notice-template.md",
  dpa: "docs/autofix/legal/DPA-template.md",
  consentWording: "docs/autofix/legal/consent-and-messaging-wording.md",
};

const entries = Object.entries(files).map(([key, path]) => `  ${key}: ${JSON.stringify(readFileSync(`${root}${path}`, "utf8"))},`);
const output = `// Generated by scripts/sync-legal-copy.mjs from docs/autofix/legal/. Do not edit by hand.
export const LEGAL_SOURCES = {
${entries.join("\n")}
} as const;

export const LEGAL_SOURCE_FILES = ${JSON.stringify(files, null, 2)} as const;
`;
writeFileSync(`${root}src/lib/legal/sources.generated.ts`, output);
